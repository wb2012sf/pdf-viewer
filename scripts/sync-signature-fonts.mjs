// Copies the cursive faces used by the "Type" tab of the signature dialog out
// of node_modules and into public/, together with a stylesheet that registers
// them.
//
// They live in public/ rather than being imported through Vite because the
// viewer takes a *stylesheet URL* and the stylesheet references the font files
// relatively — both need stable, unhashed names. Same reasoning as the OCR
// language data.
//
// Run with: node scripts/sync-signature-fonts.mjs
import { copyFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const FACES = [
  { family: 'Caveat', pkg: '@fontsource/caveat', file: 'caveat-latin-400-normal.woff2' },
  { family: 'Dancing Script', pkg: '@fontsource/dancing-script', file: 'dancing-script-latin-400-normal.woff2' },
  { family: 'Great Vibes', pkg: '@fontsource/great-vibes', file: 'great-vibes-latin-400-normal.woff2' },
  { family: 'Pacifico', pkg: '@fontsource/pacifico', file: 'pacifico-latin-400-normal.woff2' },
];

const outDir = fileURLToPath(new URL('../public/fonts/', import.meta.url));
await mkdir(outDir, { recursive: true });

for (const face of FACES) {
  const from = fileURLToPath(new URL(`../node_modules/${face.pkg}/files/${face.file}`, import.meta.url));
  await copyFile(from, `${outDir}${face.file}`);
  console.log(`copied ${face.file}`);
}

const css = [
  '/* Generated by scripts/sync-signature-fonts.mjs — do not edit by hand. */',
  '/* Cursive faces for the signature dialog, served locally so the app makes',
  '   no request to Google Fonts. All four are SIL Open Font License 1.1. */',
  '',
  ...FACES.map((face) =>
    [
      '@font-face {',
      `  font-family: '${face.family}';`,
      '  font-style: normal;',
      '  font-weight: 400;',
      '  font-display: swap;',
      `  src: url('./${face.file}') format('woff2');`,
      '}',
      '',
    ].join('\n'),
  ),
].join('\n');

await writeFile(`${outDir}signature-fonts.css`, css);
console.log('wrote signature-fonts.css');
